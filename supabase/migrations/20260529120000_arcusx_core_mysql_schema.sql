GRANT ALL ON TABLE public.arcusx_user_skills TO postgres, service_role;
GRANT ALL ON TABLE public.arcusx_user_statistics TO postgres, service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

COMMENT ON TABLE public.arcusx_users IS 'Core users migrated from MySQL; operational access via service_role / Edge Functions only.';
